def chaikin(pts, it=2, closed=True):
    pts = [tuple(p) for p in pts]
    for _ in range(it):
        out = []
        n = len(pts)
        rng = range(n) if closed else range(n - 1)
        if not closed:
            out.append(pts[0])
        for i in rng:
            a, b = np.array(pts[i]), np.array(pts[(i + 1) % n])
            out.append(tuple(a * 0.75 + b * 0.25))
            out.append(tuple(a * 0.25 + b * 0.75))
        if not closed:
            out.append(pts[-1])
        pts = out
    return pts


def circle2(r, n, cx=0.0, cy=0.0, a0=0.0):
    return [(cx + r * math.cos(a0 + 2 * PI * i / n), cy + r * math.sin(a0 + 2 * PI * i / n)) for i in range(n)]


def ellipse2(rx, ry, n, cx=0.0, cy=0.0, a0=0.0):
    return [(cx + rx * math.cos(a0 + 2 * PI * i / n), cy + ry * math.sin(a0 + 2 * PI * i / n)) for i in range(n)]


def star2(n, R, r, a0=PI / 2, rounding=1, cx=0.0, cy=0.0):
    pts = []
    for i in range(2 * n):
        rr = R if i % 2 == 0 else r
        a = a0 + PI * i / n
        pts.append((cx + rr * math.cos(a), cy + rr * math.sin(a)))
    if rounding:
        pts = round_corners(pts, rounding)
    return pts


def round_corners(pts, k=1, frac=0.22, steps=2):
    """Each corner replaced by a little arc (a quadratic between points at frac of the two edges)."""
    out = []
    n = len(pts)
    for i in range(n):
        p0, p1, p2 = np.array(pts[i - 1]), np.array(pts[i]), np.array(pts[(i + 1) % n])
        a = p1 + (p0 - p1) * frac
        b = p1 + (p2 - p1) * frac
        for s in range(steps + 1):
            t = s / steps
            q = (1 - t) ** 2 * a + 2 * (1 - t) * t * p1 + t * t * b
            out.append(tuple(q))
    return out


def poly_area2(pts):
    a = 0.0
    for i in range(len(pts)):
        x0, y0 = pts[i]
        x1, y1 = pts[(i + 1) % len(pts)]
        a += x0 * y1 - x1 * y0
    return a * 0.5


def ccw(pts):
    return pts if poly_area2(pts) > 0 else pts[::-1]


def offset2(pts, d):
    """The outline moved inward by d (pts counter-clockwise), mitred, clamped."""
    n = len(pts)
    P = np.array(pts, float)
    out = []
    for i in range(n):
        a, b, c = P[i - 1], P[i], P[(i + 1) % n]
        e1, e2 = b - a, c - b
        n1 = np.array([-e1[1], e1[0]]) / (np.linalg.norm(e1) + 1e-12)
        n2 = np.array([-e2[1], e2[0]]) / (np.linalg.norm(e2) + 1e-12)
        nm = n1 + n2
        ln = np.linalg.norm(nm)
        if ln < 1e-6:
            nm = n1
        else:
            nm = nm / ln
        cosh = max(0.35, float(np.dot(nm, n1)))
        out.append(tuple(b + nm * d / cosh))
    return out


def earclip(pts):
    """Triangles (index triples) of a simple CCW polygon."""
    idx = list(range(len(pts)))
    P = [np.array(p, float) for p in pts]
    tris = []

    def cross(o, a, b):
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0])

    def inside(p, a, b, c):
        return cross(a, b, p) >= -1e-12 and cross(b, c, p) >= -1e-12 and cross(c, a, p) >= -1e-12

    guard = 0
    while len(idx) > 3 and guard < 10000:
        guard += 1
        best = None
        for k in range(len(idx)):
            i0, i1, i2 = idx[k - 1], idx[k], idx[(k + 1) % len(idx)]
            a, b, c = P[i0], P[i1], P[i2]
            if cross(a, b, c) <= 1e-12:
                continue
            ok = True
            for j in idx:
                if j in (i0, i1, i2):
                    continue
                if inside(P[j], a, b, c):
                    ok = False
                    break
            if ok:
                # prefer the fattest ear (fewer slivers)
                e = [np.linalg.norm(b - a), np.linalg.norm(c - b), np.linalg.norm(a - c)]
                q = cross(a, b, c) / (max(e) ** 2 + 1e-12)
                if best is None or q > best[0]:
                    best = (q, k)
        if best is None:
            break
        k = best[1]
        tris.append((idx[k - 1], idx[k], idx[(k + 1) % len(idx)]))
        idx.pop(k)
    if len(idx) == 3:
        tris.append(tuple(idx))
    return tris


# ---- 3D helpers --------------------------------------------------------------------------------------------------
def rotm(axis, deg):
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    if axis == "x":
        return np.array([[1, 0, 0], [0, c, -s], [0, s, c]])
    if axis == "y":
        return np.array([[c, 0, s], [0, 1, 0], [-s, 0, c]])
    return np.array([[c, -s, 0], [s, c, 0], [0, 0, 1]])


class Part:
    """Vertices (n x 3) and faces ((indices...), material)."""

    def __init__(self, v=None, f=None):
        self.v = np.zeros((0, 3)) if v is None else np.array(v, float).reshape(-1, 3)
        self.f = [] if f is None else list(f)
        self.uv = None          # explicit texture coordinates (n x 2, NaN: projected), or None

    def copy(self):
        p = Part(self.v.copy(), list(self.f))
        p.uv = None if self.uv is None else self.uv.copy()
        return p

    def uvs(self):
        return self.uv if self.uv is not None else np.full((len(self.v), 2), np.nan)

    def add(self, *others):
        for o in others:
            n = len(self.v)
            if self.uv is not None or getattr(o, "uv", None) is not None:
                self.uv = np.vstack([self.uvs()[:n], o.uvs()])
            self.v = np.vstack([self.v, o.v]) if len(o.v) else self.v
            self.f += [(tuple(i + n for i in idx), m) for idx, m in o.f]
        return self

    def tr(self, x=0.0, y=0.0, z=0.0):
        self.v = self.v + np.array([x, y, z])
        return self

    def sc(self, x, y=None, z=None):
        y = x if y is None else y
        z = x if z is None else z
        self.v = self.v * np.array([x, y, z])
        if x * y * z < 0:
            self.flip()
        return self

    def rot(self, axis, deg):
        self.v = self.v @ rotm(axis, deg).T
        return self

    def mapv(self, fn):
        self.v = np.array([fn(p) for p in self.v], float).reshape(-1, 3)
        return self

    def flip(self):
        self.f = [(tuple(reversed(idx)), m) for idx, m in self.f]
        return self

    def mirror_x(self):
        return self.sc(-1, 1, 1)

    def mat(self, m):
        self.f = [(idx, m) for idx, _ in self.f]
        return self

    def remat(self, old, new):
        self.f = [(idx, new if m == old else m) for idx, m in self.f]
        return self

    def volume(self):
        vol = 0.0
        for idx, _ in self.f:
            p0 = self.v[idx[0]]
            for k in range(1, len(idx) - 1):
                vol += np.dot(p0, np.cross(self.v[idx[k]], self.v[idx[k + 1]]))
        return vol / 6.0

    def orient(self):
        if self.volume() < 0:
            self.flip()
        return self

    def ntris(self):
        return sum(len(idx) - 2 for idx, _ in self.f)

    def bbox(self):
        return self.v.min(axis=0), self.v.max(axis=0)


def merge(*parts):
    p = Part()
    for q in parts:
        p.add(q)
    return p


def _matfn(mat):
    if callable(mat):
        return mat
    return lambda i, j, c: mat


def loft(rings, mat="paint1", cap0=True, cap1=True, cap_mat=None, orient=True, closed=True):
    """Bands of faces through the rings (each n points, or 1 point: an apex); caps: a fan to the centre."""
    mf = _matfn(mat)
    p = Part()
    verts = []
    starts = []
    for r in rings:
        r = np.array(r, float).reshape(-1, 3)
        starts.append(len(verts))
        verts.extend(list(r))
    p.v = np.array(verts)
    faces = []
    for i in range(len(rings) - 1):
        a, b = starts[i], starts[i + 1]
        na, nb = len(np.array(rings[i]).reshape(-1, 3)), len(np.array(rings[i + 1]).reshape(-1, 3))
        n = max(na, nb)
        jm = n if closed else n - 1
        for j in range(jm):
            j1 = (j + 1) % n
            if na == 1:
                idx = (a, b + j1, b + j)
            elif nb == 1:
                idx = (a + j, a + j1, b)
            else:
                idx = (a + j, a + j1, b + j1, b + j)
            c = p.v[list(idx)].mean(axis=0)
            faces.append((idx, mf(i, j, c)))
    cm = cap_mat
    for which, do in ((0, cap0), (len(rings) - 1, cap1)):
        r = np.array(rings[which], float).reshape(-1, 3)
        if not do or len(r) < 3:
            continue
        ctr = r.mean(axis=0)
        ci = len(p.v)
        p.v = np.vstack([p.v, ctr])
        s = starts[which]
        n = len(r)
        m = cm if cm is not None else mf(which, 0, ctr)
        for j in range(n):
            # (the first cap turned the other way: both caps face out of the loft)
            faces.append(((s + j, s + (j + 1) % n, ci) if which else (s + (j + 1) % n, s + j, ci), m))
    p.f = faces
    if orient:
        p.orient()
    return p


def superellipse(hw, hh, n=16, p=2.0, pb=None, hb=None, cx=0.0, cy=0.0, z=0.0, angles=None, a0=0.0):
    """A ring in the XY plane at z: half width hw, half height hh (hb: below), exponent p (pb: below)."""
    pts = []
    if angles is None:
        angles = [a0 + 2 * PI * i / n for i in range(n)]
    for a in angles:
        c, s = math.cos(a), math.sin(a)
        pe = p if s >= 0 or pb is None else pb
        h = hh if s >= 0 or hb is None else hb
        x = hw * math.copysign(abs(c) ** (2.0 / pe), c)
        y = h * math.copysign(abs(s) ** (2.0 / pe), s)
        pts.append((cx + x, cy + y, z))
    return pts


def revolve(profile, segs=16, mat="silver", a0=0.0, orient=True, cap0=True, cap1=True, cap_mat=None):
    """Around +Y: profile = [(radius, y), ...] from bottom to top (radius 0: an apex)."""
    rings = []
    for r, y in profile:
        if r <= 1e-9:
            rings.append([(0.0, y, 0.0)])
        else:
            rings.append([(r * math.cos(a0 + 2 * PI * k / segs), y, -r * math.sin(a0 + 2 * PI * k / segs)) for k in range(segs)])
    return loft(rings, mat, cap0=cap0, cap1=cap1, cap_mat=cap_mat, orient=orient)


def sphere(r=1.0, segs=12, rings=8, mat="white", rx=None, ry=None, rz=None):
    prof = []
    for i in range(rings + 1):
        a = -PI / 2 + PI * i / rings
        prof.append((math.cos(a) if 0 < i < rings else 0.0, math.sin(a)))
    p = revolve(prof, segs, mat)
    p.sc(rx if rx is not None else r, ry if ry is not None else r, rz if rz is not None else r)
    return p


def dome(r=1.0, segs=12, rings=4, mat="white", base=True):
    """A half sphere on y = 0 (its flat base closed)."""
    prof = []
    for i in range(rings + 1):
        a = PI / 2 * i / rings
        prof.append((math.cos(a) if i < rings else 0.0, math.sin(a)))
    return revolve(prof, segs, mat).sc(r)


def torus(R, r, segs=16, rsegs=8, mat="silver"):
    rings = []
    for i in range(segs):
        a = 2 * PI * i / segs
        ring = []
        for k in range(rsegs):
            b = 2 * PI * k / rsegs
            rr = R + r * math.cos(b)
            ring.append((rr * math.cos(a), r * math.sin(b), -rr * math.sin(a)))
        rings.append(ring)
    rings.append(rings[0])
    p = loft(rings, mat, cap0=False, cap1=False, orient=False)
    # the last ring repeats the first: weld by re-indexing
    n = len(rings) - 1
    p.v = p.v[: n * rsegs]
    p.f = [(tuple(i % (n * rsegs) for i in idx), m) for idx, m in p.f]
    return p.orient()


def rounded_box(sx, sy, sz, r, k=3, mat="paint1", matfn=None):
    """A box sx x sy x sz centred on the origin, its edges rounded by r (k steps a quarter)."""
    r = min(r, sx / 2 - 1e-4, sy / 2 - 1e-4, sz / 2 - 1e-4)
    cx, cy, cz = sx / 2 - r, sy / 2 - r, sz / 2 - r
    lons = []
    for q in range(4):
        for i in range(k + 1):
            lons.append((q * PI / 2 + PI / 2 * i / k, q))
    lats = []
    for h in range(2):
        for i in range(k + 1):
            lats.append((-PI / 2 + h * PI / 2 + PI / 2 * i / k, h))
    rings = []
    for la, h in lats:
        ring = []
        for lo, q in lons:
            nx, ny, nz = math.cos(la) * math.cos(lo), math.sin(la), -math.cos(la) * math.sin(lo)
            qx = 1 if q in (0, 3) else -1
            qz = -1 if q in (0, 1) else 1
            ring.append((qx * cx + r * nx, (cy if h == 1 else -cy) + r * ny, qz * cz + r * nz))
        rings.append(ring)
    p = loft(rings, matfn or mat, cap0=True, cap1=True)
    return p


def frame_along(path):
    """Parallel-transport frames (tangent, normal, binormal) along a polyline."""
    P = np.array(path, float)
    n = len(P)
    T = []
    for i in range(n):
        if i == 0:
            t = P[1] - P[0]
        elif i == n - 1:
            t = P[-1] - P[-2]
        else:
            t = P[i + 1] - P[i - 1]
        T.append(t / (np.linalg.norm(t) + 1e-12))
    up = np.array([0, 1, 0.0]) if abs(T[0][1]) < 0.9 else np.array([1, 0, 0.0])
    N = [np.cross(T[0], np.cross(up, T[0]))]
    N[0] = np.cross(up, T[0])
    N[0] /= np.linalg.norm(N[0])
    for i in range(1, n):
        b = np.cross(T[i - 1], T[i])
        nn = N[-1]
        if np.linalg.norm(b) > 1e-8:
            b /= np.linalg.norm(b)
            ang = math.acos(max(-1, min(1, float(np.dot(T[i - 1], T[i])))))
            nn = nn @ rotm_axis(b, ang).T
        N.append(nn / np.linalg.norm(nn))
    B = [np.cross(T[i], N[i]) for i in range(n)]
    return P, T, N, B


def rotm_axis(axis, ang):
    axis = np.array(axis, float) / np.linalg.norm(axis)
    x, y, z = axis
    c, s = math.cos(ang), math.sin(ang)
    C = 1 - c
    return np.array([[c + x * x * C, x * y * C - z * s, x * z * C + y * s],
                     [y * x * C + z * s, c + y * y * C, y * z * C - x * s],
                     [z * x * C - y * s, z * y * C + x * s, c + z * z * C]])


def tube(path, radius, segs=10, mat="silver", round0=False, round1=False, cap0=True, cap1=True, rsteps=3, sx=1.0):
    """A tube along a polyline; radius: a number, a list or a function of t in 0..1; round ends: half-spheres."""
    P, T, N, B = frame_along(path)
    n = len(P)
    seg_len = np.r_[0, np.cumsum(np.linalg.norm(np.diff(P, axis=0), axis=1))]
    L = seg_len[-1] if seg_len[-1] > 0 else 1.0

    def rad(i):
        if callable(radius):
            return radius(seg_len[i] / L)
        if isinstance(radius, (list, tuple, np.ndarray)):
            return radius[i]
        return radius

    def ring(c, nn, bb, r):
        return [tuple(c + r * sx * math.cos(2 * PI * k / segs) * nn + r * math.sin(2 * PI * k / segs) * bb) for k in range(segs)]

    rings = []
    if round0:
        r0 = rad(0)
        for s in range(rsteps, 0, -1):
            a = PI / 2 * s / rsteps
            if s == rsteps:
                rings.append([tuple(P[0] - T[0] * r0)])
            else:
                rings.append(ring(P[0] - T[0] * r0 * math.sin(a), N[0], B[0], r0 * math.cos(a)))
    for i in range(n):
        rings.append(ring(P[i], N[i], B[i], rad(i)))
    if round1:
        r1 = rad(n - 1)
        for s in range(1, rsteps + 1):
            a = PI / 2 * s / rsteps
            if s == rsteps:
                rings.append([tuple(P[-1] + T[-1] * r1)])
            else:
                rings.append(ring(P[-1] + T[-1] * r1 * math.sin(a), N[-1], B[-1], r1 * math.cos(a)))
    return loft(rings, mat, cap0=cap0, cap1=cap1)


def slab(outline, thick, bevel=None, steps=2, mat="paint1", side_mat=None, top_mat=None, bot_mat=None):
    """A flat piece: a 2D outline (u, v) extruded along w (-thick/2..thick/2) with rounded edges.
    Returned in (x=u, y=v, z=w); move it with rot / tr. bevel: the rounding radius (default thick/2)."""
    outline = ccw([tuple(p) for p in outline])
    h = thick / 2.0
    r = h if bevel is None else min(bevel, h)
    layers = []  # (inset, w)
    for s in range(steps + 1):  # bottom rounding: from the bottom face's edge to the middle
        a = -PI / 2 + PI / 2 * s / steps
        layers.append((r * (1 - math.cos(a)), -h + r + r * math.sin(a) if r > 0 else -h))
    if h - r > 1e-6:
        layers.append((0.0, h - r))
    for s in range(1, steps + 1):
        a = PI / 2 * s / steps
        layers.append((r * (1 - math.cos(a)), h - r + r * math.sin(a)))
    rings = []
    for inset, w in layers:
        o = offset2(outline, inset) if inset > 1e-6 else outline
        rings.append([(u, v, w) for u, v in o])
    sm = side_mat or mat
    p = loft(rings, sm, cap0=False, cap1=False, orient=False)
    n = len(outline)
    # the two faces, ear-clipped
    for which, wm in ((0, bot_mat or mat), (len(rings) - 1, top_mat or mat)):
        ring2 = [(q[0], q[1]) for q in rings[which]]
        tris = earclip(ring2)
        s0 = which * n
        for t in tris:
            idx = (s0 + t[0], s0 + t[1], s0 + t[2])
            if which == 0:
                idx = idx[::-1]
            p.f.append((idx, wm))
    return p.orient()


def surface_shell(fn, u0, u1, v0, v1, nu, nv, thick, mat="glass"):
    """A thin closed shell from a parametric surface fn(u, v) -> point (outer), offset inward by thick along
    the surface normal: windscreens, canopies' bands."""
    U = np.linspace(u0, u1, nu + 1)
    V = np.linspace(v0, v1, nv + 1)
    outer = np.array([[fn(u, v) for v in V] for u in U], float)
    # normals by finite differences
    inner = np.zeros_like(outer)
    for i in range(nu + 1):
        for j in range(nv + 1):
            du = outer[min(i + 1, nu), j] - outer[max(i - 1, 0), j]
            dv = outer[i, min(j + 1, nv)] - outer[i, max(j - 1, 0)]
            nn = np.cross(du, dv)
            nn /= np.linalg.norm(nn) + 1e-12
            inner[i, j] = outer[i, j] - nn * thick
    p = Part()
    p.v = np.vstack([outer.reshape(-1, 3), inner.reshape(-1, 3)])
    off = (nu + 1) * (nv + 1)

    def I(i, j, s=0):
        return s * off + i * (nv + 1) + j

    for i in range(nu):
        for j in range(nv):
            p.f.append(((I(i, j), I(i + 1, j), I(i + 1, j + 1), I(i, j + 1)), mat))
            p.f.append(((I(i, j, 1), I(i, j + 1, 1), I(i + 1, j + 1, 1), I(i + 1, j, 1)), mat))
    # the rims
    for i in range(nu):
        p.f.append(((I(i, 0), I(i, 0, 1), I(i + 1, 0, 1), I(i + 1, 0)), mat))
        p.f.append(((I(i, nv), I(i + 1, nv), I(i + 1, nv, 1), I(i, nv, 1)), mat))
    for j in range(nv):
        p.f.append(((I(0, j), I(0, j + 1), I(0, j + 1, 1), I(0, j, 1)), mat))
        p.f.append(((I(nu, j), I(nu, j, 1), I(nu, j + 1, 1), I(nu, j + 1)), mat))
    return p.orient()


def disc(r, n=10, mat="plasma_glow", y=0.0, down=True, rz=None):
    """A flat polygon (one face: a fan) facing down (or up)."""
    rz = r if rz is None else rz
    p = Part()
    pts = [(r * math.cos(2 * PI * k / n), y, rz * math.sin(2 * PI * k / n)) for k in range(n)]
    p.v = np.array(pts + [(0, y, 0)])
    for k in range(n):
        idx = (n, k, (k + 1) % n)  # seen from below: ccw for k increasing in xz? fix by normal
        p.f.append((idx, mat))
    # normal of the first face
    a, b, c = p.v[n], p.v[0], p.v[1]
    nn = np.cross(b - a, c - a)
    if (nn[1] > 0) == down:
        p.flip()
    return p


def decal_on(part, center, normal, up=(0, 1, 0), lift=0.004):
    """Places a flat detail made in the XY plane facing +Z (its origin its centre) on a surface point."""
    normal = np.array(normal, float)
    normal /= np.linalg.norm(normal)
    up = np.array(up, float)
    x = np.cross(up, normal)
    if np.linalg.norm(x) < 1e-6:
        x = np.array([1.0, 0, 0])
    x /= np.linalg.norm(x)
    y = np.cross(normal, x)
    M = np.stack([x, y, normal], axis=1)
    q = part.copy()
    q.v = q.v @ M.T + np.array(center, float) + normal * lift
    return q


# ---- the model and its .obj ----------------------------------------------------------------------------------------
class Model:
    def __init__(self, name, title=""):
        self.name = name
        self.title = title
        self.groups = []  # (group name or None, Part)
        self.sockets = []  # (name, (x, y, z))
        self.notes = []

    def add(self, part, group=None):
        for g in self.groups:
            if g[0] == group:
                g[1].add(part)
                return self
        self.groups.append((group, part.copy()))
        return self

    def socket(self, name, x, y, z):
        self.sockets.append((name, (float(x), float(y), float(z))))
        return self

    def all(self):
        p = Part()
        for _, q in self.groups:
            p.add(q)
        return p

    def write(self, path=None, script=""):
        path = path or os.path.join(OUT_DIR, self.name + ".obj")
        os.makedirs(os.path.dirname(path), exist_ok=True)
        allp = self.all()
        lo, hi = allp.bbox()
        span = np.maximum(hi - lo, 1e-6)
        lines = []
        lines.append("# %s.obj -- Cosmo Zoom!: %s" % (self.name, self.title or self.name))
        lines.append("# Generated by tools/cosmozoom/models/%s (python3 tools/cosmozoom/models/build_all.py): do not edit." % (script or "build_all.py"))
        lines.append("# Metres, +Y up, +Z forward (the left is +X), faces counter-clockwise seen from outside.")
        lines.append("# MIT License -- Copyright (c) 2026 Stephane Wegener and the Onyx contributors (docs/LICENSING.md).")
        for n in self.notes:
            lines.append("# " + n)
        lines.append("mtllib cosmo.mtl")
        for nm, (x, y, z) in self.sockets:
            lines.append("#@ %s %.3f %.3f %.3f" % (nm, x, y, z))
        vbase = 0
        body = []
        ntri = 0
        vlines = []
        for gname, part in self.groups:
            V, F = weld(part)
            for x, y, z in V:
                vlines.append("v %.4f %.4f %.4f" % (x, y, z))
            for (x, y, z), t in zip(V, weld.uv):
                if np.isnan(t[0]):
                    vlines.append("vt %.4f %.4f" % ((z - lo[2]) / span[2], (y - lo[1]) / span[1]))
                else:
                    vlines.append("vt %.4f %.4f" % (t[0], t[1]))
            if gname:
                body.append("o %s" % gname)
            bymat = {}
            for idx, m in F:
                bymat.setdefault(m, []).append(idx)
            for m in sorted(bymat):
                body.append("usemtl %s" % m)
                for idx in bymat[m]:
                    body.append("f " + " ".join("%d/%d" % (i + 1 + vbase, i + 1 + vbase) for i in idx))
                    ntri += 1
            vbase += len(V)
        with open(path, "w") as f:
            f.write("\n".join(lines + vlines + body) + "\n")
        self.ntri = ntri
        return ntri


def tri_area(a, b, c):
    return 0.5 * np.linalg.norm(np.cross(b - a, c - a))


def weld(part, eps=1e-5):
    """Shared positions merged; faces as triangles (quads split on the shorter diagonal), degenerate ones dropped."""
    key = {}
    V = []
    UV = []
    remap = []
    uvs = part.uvs()
    for p, t in zip(part.v, uvs):
        k = tuple(np.round(p / eps).astype(np.int64))
        if not np.isnan(t[0]):
            k = k + tuple(np.round(t / 1e-4).astype(np.int64))
        if k not in key:
            key[k] = len(V)
            V.append(p)
            UV.append(t)
        remap.append(key[k])
    V = np.array(V)
    weld.uv = np.array(UV)
    F = []
    for idx, m in part.f:
        ids = [remap[i] for i in idx]
        # drop repeats
        clean = []
        for i in ids:
            if not clean or clean[-1] != i:
                clean.append(i)
        if len(clean) > 1 and clean[0] == clean[-1]:
            clean.pop()
        if len(clean) < 3:
            continue
        tris = []
        if len(clean) == 4:
            a, b, c, d = clean
            if np.linalg.norm(V[a] - V[c]) <= np.linalg.norm(V[b] - V[d]):
                tris = [(a, b, c), (a, c, d)]
            else:
                tris = [(a, b, d), (b, c, d)]
        else:
            for k in range(1, len(clean) - 1):
                tris.append((clean[0], clean[k], clean[k + 1]))
        for t in tris:
            if len(set(t)) < 3:
                continue
            if tri_area(V[t[0]], V[t[1]], V[t[2]]) < 1e-9:
                continue
            F.append((t, m))
    return V, F


# ---- reading back (the previews' assembly) ------------------------------------------------------------------------
def read_obj(path):
    V, F, S = [], [], []
    mat, grp = "paint1", None
    for line in open(path):
        t = line.split()
        if not t:
            continue
        if t[0] == "v":
            V.append([float(x) for x in t[1:4]])
        elif t[0] == "f":
            F.append((tuple(int(x.split("/")[0]) - 1 for x in t[1:]), mat, grp))
        elif t[0] == "usemtl":
            mat = t[1]
        elif t[0] == "o":
            grp = t[1]
        elif t[0] == "#@":
            S.append((t[1], tuple(float(x) for x in t[2:5])))
    return np.array(V), F, S
