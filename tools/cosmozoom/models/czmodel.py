def hex_kd(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4))


def write_mtl(path=None):
    path = path or os.path.join(OUT_DIR, "cosmo.mtl")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("# cosmo.mtl -- Cosmo Zoom!'s shared materials (DESIGN.md 3.2). Generated by\n")
        f.write("# tools/cosmozoom/models/czmodel.py: do not edit by hand.\n")
        f.write("# paint1 / paint2: the player's two colours (recoloured by the game); *_glow: unlit, added;\n")
        f.write("# glass: see-through; Ke > 0: unlit and not outlined (the faces' small details).\n")
        f.write("# MIT License -- Copyright (c) 2026 Stephane Wegener and the Onyx contributors (docs/LICENSING.md).\n")
        for name, hx, extra in MATERIALS:
            r, g, b = hex_kd(hx)
            f.write("\nnewmtl %s\nKd %.3f %.3f %.3f\n" % (name, r, g, b))
            if extra:
                f.write(extra + "\n")
            if name.endswith("_glow"):
                f.write("Ke %.3f %.3f %.3f\n" % (r, g, b))
    return path


# ---- smooth 1D curves --------------------------------------------------------------------------------------------
class Curve:
    """A smooth curve through (t, value) keys: monotone cubic (no overshoot)."""

    def __init__(self, keys):
        keys = sorted(keys)
        self.t = np.array([k[0] for k in keys], float)
        self.y = np.array([k[1] for k in keys], float)
        n = len(self.t)
        h = np.diff(self.t)
        d = np.diff(self.y) / h
        m = np.zeros(n)
        if n > 1:
            m[0], m[-1] = d[0], d[-1]
            for i in range(1, n - 1):
                if d[i - 1] * d[i] <= 0:
                    m[i] = 0
                else:
                    w1, w2 = 2 * h[i] + h[i - 1], h[i] + 2 * h[i - 1]
                    m[i] = (w1 + w2) / (w1 / d[i - 1] + w2 / d[i])
        self.m = m

    def __call__(self, x):
        t, y, m = self.t, self.y, self.m
        if x <= t[0]:
            return float(y[0] + m[0] * (x - t[0])) if False else float(y[0])
        if x >= t[-1]:
            return float(y[-1])
        i = int(np.searchsorted(t, x) - 1)
        h = t[i + 1] - t[i]
        s = (x - t[i]) / h
        h00 = 2 * s ** 3 - 3 * s ** 2 + 1
        h10 = s ** 3 - 2 * s ** 2 + s
        h01 = -2 * s ** 3 + 3 * s ** 2
        h11 = s ** 3 - s ** 2
        return float(h00 * y[i] + h10 * h * m[i] + h01 * y[i + 1] + h11 * h * m[i + 1])


def smoothstep(a, b, x):
    t = min(1.0, max(0.0, (x - a) / (b - a)))
    return t * t * (3 - 2 * t)


