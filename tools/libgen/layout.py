# layout.py -- the layout lock of a C++ shared library (docs/SHARED-LIBS-PLAN.md section 5.4): the
# size of every class of the library's headers (and a few offsets), written as static_asserts into a
# file compiled with the library. A program is built with these sizes and offsets: when one moves,
# the library no longer fits the programs already built -- its build fails there.
#
#   python3 tools/libgen/layout.py --cxx aarch64-none-elf-g++ --flags "..." --umbrella wtk/wtk.h \
#       --ns wtk --headers 'wtk/*.h' --offsets Widget:canvas,left,parent,ext Canvas:px,ext \
#       --out wtk/layout_lock.cpp [--update]
#
# Without --update: the file is only made when it does not exist (the first time). With --update:
# rewritten from the headers as they are now -- do it ONLY for a change that keeps old programs
# working (a class ADDED), never to make a failing build pass: a class whose size changed breaks
# every program built before (use the reserve, wtk/abi.h, or make it another library).
import argparse, glob, os, re, subprocess, sys, tempfile

ap = argparse.ArgumentParser ()
ap.add_argument ("--cxx", required = True)
ap.add_argument ("--flags", default = "")
ap.add_argument ("--umbrella", required = True)
ap.add_argument ("--ns", required = True)
ap.add_argument ("--headers", required = True)
ap.add_argument ("--offsets", nargs = "*", default = [])
ap.add_argument ("--out", required = True)
ap.add_argument ("--update", action = "store_true")
a = ap.parse_args ()
if os.path.exists (a.out) and not a.update:
	sys.exit (0)

classes = set ()
for h in glob.glob (a.headers):
	for m in re.finditer (r"^(?:class|struct)\s+([A-Z]\w*)\s*(?::[^;{]*)?\{", open (h, encoding = "utf-8").read (), re.M):
		classes.add (m.group (1))
classes = sorted (classes)
offs = []
for o in a.offsets:
	c, fields = o.split (":")
	offs += [(c, f) for f in fields.split (",")]

hdrs = ['#include "%s"' % a.umbrella] + ['#include "%s"' % h.replace ("\\", "/") for h in sorted (glob.glob (a.headers))]
probe = ['#include "onyxpp.hpp"'] + hdrs
for c in classes:
	probe.append ("extern const unsigned long wk_sz_%s; const unsigned long wk_sz_%s = sizeof (%s::%s);" % (c, c, a.ns, c))
for c, f in offs:
	probe.append ("extern const unsigned long wk_of_%s_%s; const unsigned long wk_of_%s_%s = __builtin_offsetof (%s::%s, %s);"
		      % (c, f, c, f, a.ns, c, f))
with tempfile.TemporaryDirectory () as d:
	src = os.path.join (d, "probe.cpp")
	open (src, "w").write ("\n".join (probe) + "\n")
	r = subprocess.run ([a.cxx] + a.flags.split () + ["-w", "-Wno-invalid-offsetof", "-S", src, "-o", os.path.join (d, "probe.s")],
			    capture_output = True, text = True)
	if r.returncode != 0:
		sys.exit ("layout.py: the probe does not compile:\n" + r.stderr[-3000:])
	asm = open (os.path.join (d, "probe.s")).read ()
val = dict ((m.group (1), int (m.group (2))) for m in re.finditer (r"^(wk_(?:sz|of)_\w+):\s*\n\s*\.xword\s+(\d+)", asm, re.M))

out = ["// %s -- GENERATED by tools/libgen/layout.py: the layout lock of the shared library." % os.path.basename (a.out),
       "// The programs built against the library allocate, derive and read these classes with THESE sizes",
       "// and offsets (wtk/abi.h). A static_assert that fails here means the change breaks every program",
       "// already built: put the new field in the reserve instead (Widget::reserved_ / ext...). Only a class",
       "// ADDED is a reason to regenerate this file (make wtk-layout-update).",
       "#ifdef ONYX_LIB_BUILD",
       '#include "onyxpp.hpp"'] + hdrs + [""]
for c in classes:
	out.append ('static_assert (sizeof (%s::%s) == %d, "sizeof (%s) changed: programs built before break (wtk/abi.h)");'
		    % (a.ns, c, val.get ("wk_sz_" + c, 0), c))
out.append ("#pragma GCC diagnostic ignored \"-Winvalid-offsetof\"")
for c, f in offs:
	out.append ('static_assert (__builtin_offsetof (%s::%s, %s) == %d, "%s::%s moved: programs built before break (wtk/abi.h)");'
		    % (a.ns, c, f, val.get ("wk_of_%s_%s" % (c, f), 0), c, f))
out += ["#endif", ""]
open (a.out, "w", encoding = "utf-8", newline = "\n").write ("\n".join (out))
print ("layout.py: %s: %d classes, %d offsets" % (a.out, len (classes), len (offs)))
